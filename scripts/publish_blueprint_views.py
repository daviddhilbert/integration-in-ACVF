#!/usr/bin/env python3
"""Create public GitHub views of the mathematical blueprint and clickable graph."""
from pathlib import Path
from urllib.parse import quote
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
BP = ROOT / 'blueprint'
BASE = 'https://github.com/daviddhilbert/integration-in-ACVF/blob/main/blueprint/DEPENDENCIES.md'
manifest = json.loads((BP / 'proof-source-manifest.json').read_text())
nodes = json.loads((BP / 'nodes.json').read_text())
by_id = {n['id']: n for n in nodes}
intro = r'''# Integration in algebraically closed valued fields

## Mathematical blueprint

**[Open the dependency graph](dependency-graph.svg)** ·
**[Download the PDF](https://github.com/daviddhilbert/integration-in-ACVF/releases/download/v1.0.0/integration-in-ACVF-blueprint.pdf)**

The construction passes from definable geometry in the valued-field sort VF
to data in the leading-term sort RV. Special transformations and standard
contractions produce RV presentations; the comparison theorems make the result
independent of those choices. Common blowups determine the kernel of lifting
without volume forms. With volume forms, the kernel is generated by the basic
point-minus-cone relation, giving Theorem 7.13 in the form

$$
K(\mu\mathrm{VF}[*])\cong K(\mu\mathrm{RV}[*])/\langle[P]-[C]\rangle.
$$

Here P and C are the basic measured point and cone. The construction gives
integration in definable families, supported Fubini and change of variables,
both before and after normalization. Weighted degree-zero coefficients are
retained, including in the degree-one factorization of the principal relation.

This blueprint follows Sections 2–7 of
[Yimu Yin's paper](https://arxiv.org/abs/0809.0473v2) in the accepted scopes.
The original model, characteristic, saturation and parameter hypotheses remain
in force as specified in each linked theorem type. RV[k] has finite-to-one
volume maps with arbitrary auxiliary RV arity; 5.5 uses explicit presentation
charts; 7.5 has nonempty selected coordinates; function integration has positive
VF dimension, nonempty retained-coordinate projections and a separate total
integral. The approved corrections and the whole-field boundary of 3.17 are
recorded in [PAPER-CORRECTIONS.md](../PAPER-CORRECTIONS.md).

The graph records selected mathematical dependencies. Every node below gives
its mathematical statement, proof outline and exact Lean source links.

'''
out = [intro]
section = None
for n in nodes:
    if section != n['section']:
        section = n['section']
        out.append('## ' + section + '\n')
    out.append('<a id="' + n['id'] + '"></a>\n\n### ' + n['title'] + '\n')
    out.append(n['statement'] + '\n')
    if n['proof']:
        out.append('**Proof outline.** ' + n['proof'] + '\n')
    if n['dependencies']:
        out.append('**Uses:** ' + ', '.join('[' + by_id[d]['title'] + '](#' + d + ')' for d in n['dependencies']) + '.\n')
    out.append('<details>\n<summary>Lean declarations</summary>\n')
    for d in n['declarations']:
        url = manifest['repository'] + '/blob/' + manifest['proof_revision'] + '/' + quote(d['file'], safe='/') + '#L' + str(d['line'])
        out.append('- [`' + d['name'] + '`](' + url + ')')
    out.append('\n</details>\n')
(BP / 'DEPENDENCIES.md').write_text('\n'.join(out))
svg_ns = 'http://www.w3.org/2000/svg'
xlink_ns = 'http://www.w3.org/1999/xlink'
ET.register_namespace('', svg_ns)
ET.register_namespace('xlink', xlink_ns)
svg = ET.parse(BP / 'web/dependency-graph.svg')
seen = set()
for node in svg.getroot().iter('{' + svg_ns + '}g'):
    if node.attrib.get('class') != 'node':
        continue
    label = node.find('{' + svg_ns + '}title').text
    assert label in by_id, label
    seen.add(label)
    anchors = list(node.iter('{' + svg_ns + '}a'))
    assert anchors, label
    for anchor in anchors:
        anchor.set('{' + xlink_ns + '}href', BASE + '#' + label)
assert seen == set(by_id), 'Public graph node inventory differs'
svg.write(BP / 'dependency-graph.svg', encoding='utf-8', xml_declaration=True)
print(json.dumps({'status': 'PASS', 'public_graph_nodes': len(seen), 'statement_document': 'blueprint/DEPENDENCIES.md'}))
